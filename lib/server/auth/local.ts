/** The account the login screen names in local mode. */
export const LOCAL_ACCOUNT: LocalAccount = GPK;

export const localAccountById = (id: string): LocalAccount | undefined =>
  LOCAL_ACCOUNTS.find((a) => a.id === id);

export const localAccountByUsername = (username: string): LocalAccount | undefined =>
  LOCAL_ACCOUNTS.find((a) => a.username === username);

/**
 * The account an email names, matched without case.
 *
 * `erph.user`'s own index is on `lower(email)`, and the synced lookup runs
 * through PostgREST's `ilike` — this mirrors both so local mode answers the
 * same identifier the same way. The pentadbir is not reached by email here
 * unless they type one: they sign in by username, exactly as on a real
 * deployment.
 */
export const localAccountByEmail = (email: string): LocalAccount | undefined => {
  const needle = email.trim().toLowerCase();
  return LOCAL_ACCOUNTS.find((a) => a.email?.toLowerCase() === needle);
};

