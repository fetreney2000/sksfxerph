-- Run AFTER 001a/001b/002/…/017. Safe to run more than once.
--
-- `school_week_stats` and `school_week_history` accepted any member of the
-- school. That was deliberate — they return counts and a percentage and never
-- a name — and it was the wrong question. A Guru Biasa's dashboard is about
-- their own week: four cards and nothing about anyone else's. A school's
-- compliance percentage beside them is an answer to a question they are no
-- more able to act on than a colleague's roster, which `/api/pantau/teachers`
-- has always refused.
--
-- So the dashboard hid the card while the endpoint served it, and both had to
-- be told the same thing. `/api/stats` asks for `pantau` now, and these two
-- check for a supervisor — or the school's own Administrator, who already
-- answers for the school's figures on `/utama` and whose view
-- (`v_school_compliance`) is `security_invoker`, so leaving them out would
-- make a table they hold error rather than quietly show less.
--
-- Generated by scripts/gen-migration.py from db/schema.sql:
--
--   python scripts/gen-migration.py
--
-- ▸ 1 ▸ the two statistics functions ─────────────────────────────────────
create or replace function erph.school_week_stats(p_school uuid, p_session text, p_week smallint)
returns table (teachers int, expected int, submitted int, approved int,
               returned_t int, drafts int, compliance numeric)
language plpgsql stable security definer set search_path = erph, public as $$
declare
  v_teachers int := 0;
  v_per_week int := 5;
begin
  -- Whole-school figures are a supervisor's question, not a teacher's.
  --
  -- The check was `is_member`, which made this the one thing a Guru Biasa
  -- could still see the school through — the dashboard hid the card but the
  -- route served it. Now it is the same rule as `/api/stats`: a teacher's
  -- dashboard is about their own week, and the school's compliance percentage
  -- beside it is an answer to a question they are not the one to answer.
  --
  -- The Administrator keeps it: they already answer for the school's figures
  -- on `/utama` through `admin_list_overview`, and `v_school_compliance` is
  -- `security_invoker` — a check that ignored them would make a table they
  -- already hold error rather than quietly show less.
  if not erph.is_staff(p_school)
     and not erph.has_role(p_school, array['pentadbir']::erph.member_role[]) then
    raise exception 'Tidak dibenarkan';
  end if;

  select count(*)::int into v_teachers
    from erph.school_member
   where school_id = p_school and role = 'guru_biasa' and is_active;

  -- The school's own rule, read rather than assumed. The default only ever
  -- applies to a school whose settings row has not been created yet.
  select coalesce(max(rph_per_week), 5)::int into v_per_week
    from erph.school_setting
   where school_id = p_school;

  return query
  with d as (
    select status, grade from erph.rph_document
     where school_id = p_school and session = p_session
       and week_no = p_week and deleted_at is null
  )
  select
    v_teachers,
    (v_teachers * v_per_week)::int,
    (select count(*)::int from d where status <> 'draft'),
    (select count(*)::int from d where grade = 1),
    (select count(*)::int from d where status = 'returned' or grade = 0),
    (select count(*)::int from d where status = 'draft'),
    -- `least` ignores NULL arguments, so `least(100, NULL)` is 100 — a school
    -- with no active Guru Biasa would report full compliance instead of no
    -- figure at all. The zero denominator is therefore handled here and
    -- returns NULL: not scored, rather than scored zero or scored perfectly.
    case when v_teachers * v_per_week = 0 then null
         else least(100, round(100.0 * coalesce((select count(*) from d where grade = 1), 0)
               / (v_teachers * v_per_week), 1)) end;
end $$;

create or replace function erph.school_week_history(p_school uuid, p_session text,
                                                    p_first_week smallint,
                                                    p_last_week smallint)
returns table (week smallint, teachers int, expected int, submitted int,
               approved int, returned_t int, drafts int, compliance numeric,
               avg_minutes numeric)
language plpgsql stable security definer set search_path = erph, public as $$
begin
  -- The same permission shape as the single-week function beside it, which
  -- is to say: a supervisor, or the school's own Administrator.
  --
  -- Both checks were missing here and `is_member` elsewhere, so the school's
  -- figures were the one screen a Guru Biasa could still see the school on —
  -- the dashboard hid the card while the endpoint served it. Being SECURITY
  -- DEFINER, neither ever consulted the caller's RLS, so the check inside is
  -- the only thing standing between a stranger and a school's year: headcount,
  -- submissions, approvals, compliance and how long the school takes to
  -- review.
  if not erph.is_staff(p_school)
     and not erph.has_role(p_school, array['pentadbir']::erph.member_role[]) then
    raise exception 'Tidak dibenarkan';
  end if;

  return query
  with active as (
    select count(*)::int n from erph.school_member
     where school_id = p_school and role = 'guru_biasa' and is_active
  ), cfg as (
    -- One row even when the settings row is missing, so the join never
    -- drops a week: the default is the same five as the column's own.
    select coalesce(max(rph_per_week), 5)::int per_week
      from erph.school_setting
     where school_id = p_school
  ), docs as (
    select week_no, status, grade, submitted_at, reviewed_at
      from erph.rph_document
     where school_id = p_school and session = p_session
       and deleted_at is null
       and week_no between p_first_week and p_last_week
  )
  select w.week::smallint,
         a.n,
         (a.n * c.per_week)::int,
         count(d.*) filter (where d.status <> 'draft')::int,
         count(d.*) filter (where d.grade = 1)::int,
         count(d.*) filter (where d.status = 'returned' or d.grade = 0)::int,
         count(d.*) filter (where d.status = 'draft')::int,
         -- Same `least`/NULL trap as the week's own figure: a school with no
         -- active Guru Biasa has no denominator, so the week is unscored
         -- rather than perfect.
         case when a.n * c.per_week = 0 then null
              else least(100, round(100.0 * count(d.*) filter (where d.grade = 1)
                    / (a.n * c.per_week), 1)) end,
         round(avg(extract(epoch from (d.reviewed_at - d.submitted_at)) / 60.0)
               filter (where d.reviewed_at is not null
                       and d.submitted_at is not null
                       and d.reviewed_at >= d.submitted_at), 1)
    from generate_series(p_first_week::int, p_last_week::int) w(week)
    cross join active a
    cross join cfg c
    left join docs d on d.week_no = w.week
   group by w.week, a.n, c.per_week
   order by w.week;
end $$;
