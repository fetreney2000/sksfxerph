-- ============================================================================
-- eRPH ▸ MIGRATION 012 — the office a person holds, printed on the cover
-- ============================================================================
-- Run AFTER 001a/001b/002/003/004/005/006/007/008/009/010/011. Safe to run more
-- than once.
--
-- The JAWATAN row of the weekly cover sheet read `school_member.title`, a
-- free-text column no code path ever wrote — so every cover printed "—"
-- beneath a signature the school had actually made, on a sheet whose whole
-- point is that a district officer can tell who signed it and as what.
--
-- `erph.jawatan` is the office the school sets, and it is deliberately not
-- derived from `erph.member_role`: three different Penolong Kanan offices
-- live under the single role 'gpk', so the role cannot say which one this
-- person holds. NULL means nobody has said, and prints as "—".
--
-- The backfill covers only what the role already states outright. 'gpk' does
-- not name an office, so it stays NULL rather than being given one — a cover
-- sheet that invented an office the school never gave would be exactly the
-- failure this replaces.
--
-- Two function shapes change, and both need a drop first:
--
--   · `admin_list_members` gains a column, i.e. a new *return type*, which
--     Postgres refuses to change in place (42P13);
--   · `admin_create_member` gains a parameter, which Postgres treats as an
--     entirely different function — without the drop the old arity lingers
--     beside the new one and a call that omits the jawatan keeps resolving
--     to the version that cannot set it.
--
-- `admin_set_member` now writes `erph.user.role` too. The route guard reads
-- that column on every request while the function only ever wrote
-- `school_member.role`, so "peranan dikemas kini" was reporting half a change
-- in both directions: a promotion that never reached the review screens, a
-- demotion that never reached the session.
--
-- Generated by scripts/gen-migration.py from db/schema.sql:
--
--   python scripts/gen-migration.py
--
-- ▸ 1 ▸ the enum and the column ─────────────────────────────────────────────
-- A database built by running 001b first already has both — 001b creates them
-- so that 002 and 004 can name the type in a signature — and both statements
-- below then change nothing. They are here for a database that ran the
-- original 001b, which had no idea this column was coming.
do $$
begin
  if not exists (
    select 1 from pg_type t
      join pg_namespace n on n.oid = t.typnamespace
     where n.nspname = 'erph' and t.typname = 'jawatan'
  ) then
    create type erph.jawatan as enum (
      'guru_biasa', 'pk_pentadbiran', 'pk_hem', 'pk_kokum', 'guru_besar'
    );
  end if;
end $$;

alter table erph.user add column if not exists jawatan erph.jawatan;

-- ▸ 2 ▸ the backfill, where the role already says it ────────────────────────
update erph.user set jawatan = 'guru_biasa'
 where role = 'guru_biasa' and jawatan is null;

update erph.user set jawatan = 'guru_besar'
 where role = 'guru_besar' and jawatan is null;

-- ▸ 3 ▸ the functions ───────────────────────────────────────────────────────
drop function if exists erph.admin_list_members(uuid);
drop function if exists erph.admin_create_member(uuid, text, text, erph.member_role, text, text);

create or replace function erph.jawatan_for(p_role erph.member_role,
                                            p_jawatan erph.jawatan)
returns erph.jawatan language sql immutable set search_path = erph, public as $$
  select case
    when p_jawatan is null then null
    when p_jawatan = 'guru_biasa'   then case when p_role = 'guru_biasa' then p_jawatan end
    when p_jawatan = 'guru_besar'   then case when p_role = 'guru_besar' then p_jawatan end
    -- the three Penolong Kanan offices, all of them held under 'gpk'
    when p_role = 'gpk' then p_jawatan
    else null
  end;
$$;

create or replace function erph.admin_list_members(p_school uuid)
returns table (user_id uuid, username text, full_name text, email text,
               role erph.member_role, jawatan erph.jawatan, is_active boolean,
               last_login_at timestamptz, locked_until timestamptz,
               failed_logins int, password_changed_at timestamptz,
               supervisor_id uuid, supervisor_name text)
language sql stable security definer set search_path = erph, public as $$
  select m.user_id, u.username, u.full_name, u.email, m.role, u.jawatan,
         u.is_active, u.last_login_at, u.locked_until, u.failed_logins,
         u.password_changed_at, m.supervisor_id, sup.full_name
    from erph.school_member m
    join erph.user u on u.id = m.user_id
    left join erph.user sup on sup.id = m.supervisor_id
   where m.school_id = p_school and erph.has_role(p_school, array['pentadbir']::erph.member_role[])
   order by m.role, u.username;
$$;

create or replace function erph.admin_create_member(p_school uuid, p_username text,
                                                    p_full_name text,
                                                    p_role erph.member_role,
                                                    p_password_hash text,
                                                    p_email text default null,
                                                    p_jawatan erph.jawatan default null)
returns uuid language plpgsql security definer set search_path = erph, public as $$
declare
  v_id uuid;
  -- Login matches case-insensitively (`.ilike` in /api/auth/login), so the
  -- name is normalized here too: `GURU.BARU` must land on the "already used"
  -- check, not bounce off a format rule that rejects capitals the login
  -- screen would have accepted.
  v_username text := lower(trim(p_username));
begin
  if not erph.has_role(p_school, array['pentadbir']::erph.member_role[]) then
    raise exception 'Peranan pentadbir diperlukan';
  end if;
  if p_role = 'system' then
    raise exception 'Peranan sistem tidak boleh diberikan kepada akaun';
  end if;
  if v_username !~ '^[a-z0-9._-]{3,32}$' then
    raise exception 'Nama pengguna: 3-32 aksara, huruf kecil, nombor, titik atau tanda hubung';
  end if;
  if nullif(trim(p_full_name), '') is null then
    raise exception 'Nama penuh diperlukan';
  end if;
  -- The office may be left for later — but if it is given here it has to fit
  -- the role, or a GPK account could be born already printed as "Guru Besar".
  if p_jawatan is not null and erph.jawatan_for(p_role, p_jawatan) is distinct from p_jawatan then
    raise exception 'Jawatan tidak sepadan dengan peranan akaun';
  end if;
  if p_password_hash is null or length(p_password_hash) < 20 then
    raise exception 'Kata laluan tidak sah';
  end if;
  -- Race backstop for the app-side check: `user_username_uniq` is what actually
  -- makes this hold when two tabs submit the same name at once.
  if exists (select 1 from erph.user u where lower(u.username) = v_username) then
    raise exception 'Nama pengguna ini telah digunakan';
  end if;

  insert into erph.user (username, password_hash, full_name, email, role, jawatan)
  values (v_username, p_password_hash, trim(p_full_name),
          nullif(trim(p_email), ''), p_role, p_jawatan)
  returning id into v_id;

  insert into erph.school_member (school_id, user_id, role)
  values (p_school, v_id, p_role);

  return v_id;
end $$;

create or replace function erph.admin_set_member(p_school uuid, p_user uuid,
                                                 p_role erph.member_role,
                                                 p_active boolean)
returns void language plpgsql security definer set search_path = erph, public as $$
begin
  if not erph.has_role(p_school, array['pentadbir']::erph.member_role[]) then
    raise exception 'Peranan pentadbir diperlukan';
  end if;
  if p_role = 'system' then
    raise exception 'Peranan sistem tidak boleh diberikan kepada akaun';
  end if;
  if not exists (select 1 from erph.school_member
                 where school_id = p_school and user_id = p_user) then
    raise exception 'Akaun bukan ahli sekolah ini';
  end if;
  -- Both rows, both halves of the change. `is_active` travels with the role
  -- onto the membership as well as onto the account: every SQL policy reads
  -- `school_member.is_active`, so deactivating an account that left
  -- `school_member` active would keep a dismissed teacher in the monitoring
  -- roster, still satisfy `has_role(..., 'guru_besar')` inside the review
  -- RPCs, and still receive reminders. The route guard reads
  -- `erph.user.is_active` and would have denied them, so the two models
  -- would have disagreed about the same person.
  update erph.school_member set role = p_role, is_active = p_active
   where school_id = p_school and user_id = p_user;
  -- The jawatan travels with the role: an office the new role cannot hold is
  -- cleared rather than left for the cover sheet to print under a name that
  -- never held it. Refusing instead would turn a routine demotion into an
  -- error the administrator has no way to resolve from that screen.
  update erph.user
     set is_active = p_active,
         role = p_role,
         jawatan = erph.jawatan_for(p_role, erph.user.jawatan)
   where id = p_user;
end $$;

create or replace function erph.admin_set_jawatan(p_school uuid, p_user uuid,
                                                  p_jawatan erph.jawatan)
returns void language plpgsql security definer set search_path = erph, public as $$
declare
  v_role erph.member_role;
begin
  if not erph.has_role(p_school, array['pentadbir']::erph.member_role[]) then
    raise exception 'Peranan pentadbir diperlukan';
  end if;
  if not exists (select 1 from erph.school_member
                 where school_id = p_school and user_id = p_user) then
    raise exception 'Akaun bukan ahli sekolah ini';
  end if;
  select role into v_role from erph.user where id = p_user;
  if p_jawatan is not null and erph.jawatan_for(v_role, p_jawatan) is distinct from p_jawatan then
    raise exception 'Jawatan tidak sepadan dengan peranan akaun';
  end if;

  update erph.user set jawatan = p_jawatan where id = p_user;
end $$;
