-- ============================================================================
-- eRPH ▸ MIGRATION 019 — the administrator decides which week a date range is
-- ============================================================================
-- Run AFTER 001a/001b/002/…/018. Safe to run more than once.

-- The week number was arithmetic: seven-day blocks from Monday 16 March 2026,
-- the same for every school and every term. Right until a school's own calendar
-- disagrees with it — a term that began a fortnight earlier, a break the grid
-- did not know about — and then every figure on the dashboard, every deadline
-- and every printed sheet is confidently wrong in the same direction.
--
-- `erph.academic_calendar` already existed for exactly this and was read by
-- nothing. What it lacked was a writer a school could reach: an INSERT policy
-- cannot know that two individually valid rows contradict each other.
--
-- So the first function validates more than it writes. A declared week
-- **cascades**: 19–23 Oct as week 34 makes 26 Oct 35 and 2 Nov 36, which is
-- what keeps numbering non-decreasing with date so that only the first week
-- that moved has to be corrected. The two monotonicity checks are what refuse
-- the pair that would run backwards, and the Monday requirement is what makes
-- the 7-day step exact rather than approximately right.
--
-- `p_from_week_no` is how an edit arrives: the row currently holding this
-- Monday is deleted in the same transaction, or the upsert would leave the old
-- declaration standing under its own number and two anchors would claim one
-- date.
--
-- The week number itself is still computed in TypeScript (lib/config.ts) and
-- SQL never derives one from a date — it filters on what the client sends, as
-- it always has. These functions only keep the table honest.
--
-- Generated by scripts/gen-migration.py from db/schema.sql:
--
--   python scripts/gen-migration.py
--
-- ▸ 1 ▸ the calendar write path ─────────────────────────────────────────────
create or replace function erph.admin_set_calendar_week(p_school uuid, p_session text,
                                                        p_week_no smallint,
                                                        p_start_date date,
                                                        p_end_date date,
                                                        p_label text default null,
                                                        p_from_week_no smallint default null)
returns void language plpgsql security definer set search_path = erph, public as $$
declare
  v_prev_week  smallint;
  v_prev_start date;
  v_next_week  smallint;
  v_next_start date;
  v_min_week   smallint;
  v_max_week   smallint;
begin
  if not erph.has_role(p_school, array['pentadbir']::erph.member_role[]) then
    raise exception 'Peranan pentadbir diperlukan';
  end if;
  if p_week_no is null or p_week_no not between 1 and 52 then
    raise exception 'Minggu mesti antara 1 dan 52';
  end if;
  if p_session is null or p_session !~ '^[0-9]{4}/[0-9]{4}$' then
    raise exception 'Sesi mesti dalam bentuk TTTT/TTTT';
  end if;
  if p_start_date is null or p_end_date is null then
    raise exception 'Tarikh mula dan akhir diperlukan';
  end if;
  -- A Monday, or the 7-day cascade from this row lands mid-week and every week
  -- after it is off by a day. `isodow`: Monday = 1 … Sunday = 7.
  if extract(isodow from p_start_date) <> 1 then
    raise exception 'Tarikh mula mesti hari Isnin';
  end if;
  -- schoolDays() always renders the five days from that Monday, so a Friday
  -- that is not start + 4 would be a week whose own end date disagrees with
  -- the days it prints.
  if p_end_date <> p_start_date + 4 then
    raise exception 'Tarikh akhir mesti hari Jumaat minggu yang sama';
  end if;

  if p_from_week_no is not null then
    if not exists (select 1 from erph.academic_calendar
                    where school_id = p_school and session = p_session
                      and week_no = p_from_week_no) then
      raise exception 'Tetapan minggu lama tidak dijumpai';
    end if;
    delete from erph.academic_calendar
     where school_id = p_school and session = p_session and week_no = p_from_week_no;
  end if;

  -- The new number must be free: it may update the row already sitting on this
  -- Monday (a relabel, or the number itself), but it may not take a number that
  -- belongs to a different Monday.
  if exists (select 1 from erph.academic_calendar
              where school_id = p_school and session = p_session
                and week_no = p_week_no and start_date <> p_start_date) then
    raise exception 'Minggu % sudah ditetapkan pada tarikh lain', p_week_no;
  end if;
  -- And one date may only ever be one week.
  if exists (select 1 from erph.academic_calendar
              where school_id = p_school and session = p_session
                and start_date = p_start_date and week_no <> p_week_no) then
    raise exception 'Tarikh itu sudah ditetapkan kepada minggu lain';
  end if;

  select week_no, start_date into v_prev_week, v_prev_start
    from erph.academic_calendar
   where school_id = p_school and session = p_session and start_date < p_start_date
   order by start_date desc limit 1;

  -- Both bounds are *stated*, not described. "The previous week plus the
  -- distance between the dates" is a correct account of a constraint and a
  -- useless answer to someone who has to pick a number — the message is the
  -- one thing the person at the form can act on.
  if v_prev_week is not null then
    v_min_week := v_prev_week + ((p_start_date - v_prev_start) / 7);
    if p_week_no < v_min_week then
      raise exception 'Minggu mesti sekurang-kurangnya %', v_min_week;
    end if;
  end if;

  select week_no, start_date into v_next_week, v_next_start
    from erph.academic_calendar
   where school_id = p_school and session = p_session and start_date > p_start_date
   order by start_date asc limit 1;

  if v_next_week is not null then
    v_max_week := v_next_week - ((v_next_start - p_start_date) / 7);
    if p_week_no > v_max_week then
      raise exception 'Minggu mesti tidak melebihi %', v_max_week;
    end if;
  end if;

  insert into erph.academic_calendar (school_id, session, week_no, start_date, end_date, label)
  values (p_school, p_session, p_week_no, p_start_date, p_end_date, nullif(trim(p_label), ''))
  on conflict (school_id, session, week_no)
  do update set start_date = excluded.start_date,
                end_date   = excluded.end_date,
                label      = excluded.label;
end $$;

create or replace function erph.admin_clear_calendar_week(p_school uuid, p_session text,
                                                          p_week_no smallint)
returns void language plpgsql security definer set search_path = erph, public as $$
begin
  if not erph.has_role(p_school, array['pentadbir']::erph.member_role[]) then
    raise exception 'Peranan pentadbir diperlukan';
  end if;
  if p_week_no is null or p_week_no not between 1 and 52 then
    raise exception 'Minggu mesti antara 1 dan 52';
  end if;

  delete from erph.academic_calendar
   where school_id = p_school and session = p_session and week_no = p_week_no;
end $$;
